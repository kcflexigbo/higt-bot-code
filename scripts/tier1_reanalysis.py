"""Tier 1 re-analysis of stored test predictions (no training).

Answers the simulated-review points that need only existing outputs:

* per-scenario confusion counts, FPR, recall and MCC for every model;
* aggregates over subsets: all test nodes, all but iot23-1-1, in-pool
  chronological tails only, and the three held-out scenarios;
* seed mean +- sample SD (ddof=1) wherever several runs exist;
* model selection on validation F1 instead of test F1;
* host-level view: share of bot hosts detected in at least one window and
  windows from first appearance to first detection.

Reads data/inspection_logs/predictions/*.npz (node order = load_split_files("test")
order) and the phase*_*.json result files. Read-only with respect to results.
Output: data/inspection_logs/tier1_reanalysis.{md,json}
"""
from __future__ import annotations

import os

os.environ.setdefault("CUDA_MODULE_LOADING", "LAZY")
import torch  # noqa: E402

import json
from pathlib import Path

import numpy as np

from src.data.dataset import SplitSpec, load_split_files

INSPECTION = Path("data/inspection_logs")
PRED = INSPECTION / "predictions"
DEGENERATE = "iot23-1-1"

RUNS = {  # model -> list of npz stems (one per training run)
    "HiGT-Bot (GT-edge)": ["higt_bot_edge", "higt_bot_edge_seed1", "higt_bot_edge_seed2"],
    "SAGPool, no GT": ["sagpool"],
    "T-GINE + skip": ["t_gine_skip"],
    "GINE (flat)": ["gine", "gine_seed1", "gine_seed2", "gine_seed3"],
    "Random forest": ["rf"],
}


def counts(y, p):
    tp = int(((p == 1) & (y == 1)).sum()); fp = int(((p == 1) & (y == 0)).sum())
    fn = int(((p == 0) & (y == 1)).sum()); tn = int(((p == 0) & (y == 0)).sum())
    return tp, fp, fn, tn


def metrics(y, p):
    tp, fp, fn, tn = counts(y, p)
    f1 = 2 * tp / (2 * tp + fp + fn) if (2 * tp + fp + fn) else 0.0
    rec = tp / (tp + fn) if tp + fn else float("nan")
    fpr = fp / (fp + tn) if fp + tn else float("nan")
    den = np.sqrt(float(tp + fp) * (tp + fn) * (tn + fp) * (tn + fn))
    mcc = (tp * tn - fp * fn) / den if den else 0.0
    return {"tp": tp, "fp": fp, "fn": fn, "tn": tn, "f1": f1,
            "recall": rec, "fpr": fpr, "mcc": float(mcc)}


def mean_sd(vals):
    a = np.asarray(vals, dtype=float)
    return float(a.mean()), (float(a.std(ddof=1)) if len(a) > 1 else float("nan"))


def fmt(m, sd=None, d=4):
    if sd is None or np.isnan(sd):
        return f"{m:.{d}f}"
    return f"{m:.{d}f} ± {sd:.{d}f}"


def host_index(spec):
    """(scenario, ip, window_idx) for every test node, in npz order."""
    rows = []
    for fp in load_split_files("test", spec):
        g = torch.load(fp, weights_only=False)
        for ip in g.node_ips:
            rows.append((g.scenario, ip, int(g.window_idx)))
    return rows


def host_level(y, p, idx):
    """Per bot host: ever detected? windows from first bot appearance to first hit."""
    first_bot: dict = {}
    first_hit: dict = {}
    for k, (sc, ip, w) in enumerate(idx):
        if y[k] != 1:
            continue
        key = (sc, ip)
        first_bot[key] = min(first_bot.get(key, w), w)
        if p[k] == 1:
            first_hit[key] = min(first_hit.get(key, w), w)
    n = len(first_bot)
    det = [first_hit[k] - first_bot[k] for k in first_bot if k in first_hit]
    return {"bot_hosts": n, "detected_hosts": len(det),
            "host_recall": len(det) / n if n else float("nan"),
            "median_delay_windows": float(np.median(det)) if det else float("nan"),
            "share_detected_in_first_window": float(np.mean(np.array(det) == 0)) if det else float("nan")}


def main():
    spec = SplitSpec.load()
    held_out = set(spec.holdout_test_scenarios)
    idx = host_index(spec)
    subsets = {
        "all": lambda s: np.ones_like(s, dtype=bool),
        f"all except {DEGENERATE}": lambda s: s != DEGENERATE,
        "in-pool tails": lambda s: ~np.isin(s, list(held_out)),
        f"in-pool tails except {DEGENERATE}": lambda s: (~np.isin(s, list(held_out))) & (s != DEGENERATE),
        "held-out scenarios": lambda s: np.isin(s, list(held_out)),
    }
    out = {"subsets": {}, "per_scenario": {}, "host_level": {}, "selection": []}
    md = ["# Tier 1 re-analysis of stored test predictions", "",
          "Generated by `scripts/tier1_reanalysis.py`. SD is the sample SD (ddof=1) over training runs; "
          "a single number means one run is stored. FPR = FP/(FP+TN).", ""]

    loaded = {}
    for model, stems in RUNS.items():
        loaded[model] = [np.load(PRED / f"{s}.npz", allow_pickle=True) for s in stems
                         if (PRED / f"{s}.npz").exists()]
    scen = loaded["HiGT-Bot (GT-edge)"][0]["scenario"]
    yref = loaded["HiGT-Bot (GT-edge)"][0]["y"]
    for runs in loaded.values():
        for z in runs:
            assert np.array_equal(z["y"], yref), "prediction files are not node-aligned"
    assert len(idx) == len(yref), "host index does not match prediction length"

    # 1. subsets
    md += ["## 1. Aggregates by test subset", ""]
    for name, fn_mask in subsets.items():
        mask = fn_mask(scen)
        n = int(mask.sum()); npos = int(yref[mask].sum())
        md += [f"### {name} (nodes {n:,}, bots {npos:,}, benign {n - npos:,})", "",
               "| Model | runs | F1 | MCC | Recall | FPR | FN | FP |", "|---|---|---|---|---|---|---|---|"]
        out["subsets"][name] = {}
        for model, runs in loaded.items():
            ms = [metrics(z["y"][mask], z["pred"][mask]) for z in runs]
            agg = {k: mean_sd([m[k] for m in ms]) for k in ("f1", "mcc", "recall", "fpr", "fn", "fp")}
            out["subsets"][name][model] = {"runs": ms, "mean_sd": agg}
            md.append(f"| {model} | {len(runs)} | {fmt(*agg['f1'])} | {fmt(*agg['mcc'])} | "
                      f"{fmt(*agg['recall'])} | {fmt(*agg['fpr'])} | {fmt(*agg['fn'], d=0)} | {fmt(*agg['fp'], d=0)} |")
        md.append("")

    # 2. per scenario (first run of each model)
    md += ["## 2. Per scenario (first stored run of each model)", "",
           "| Scenario | nodes | bots | " + " | ".join(f"{m} FN/FP/MCC" for m in loaded) + " |",
           "|---|---|---|" + "---|" * len(loaded)]
    for sc in sorted(set(scen)):
        mask = scen == sc
        cells = []
        out["per_scenario"][sc] = {}
        for model, runs in loaded.items():
            m = metrics(runs[0]["y"][mask], runs[0]["pred"][mask])
            out["per_scenario"][sc][model] = m
            cells.append(f"{m['fn']}/{m['fp']}/{m['mcc']:.3f}")
        tag = " (held out)" if sc in held_out else ""
        md.append(f"| {sc}{tag} | {int(mask.sum())} | {int(yref[mask].sum())} | " + " | ".join(cells) + " |")
    md.append("")

    # 3. per-dataset macro MCC (mean over scenarios with both classes)
    md += ["## 3. Per-dataset macro MCC (mean over scenarios that contain both classes)", "",
           "| Model | " + " | ".join(("ctu13", "iot23", "medbiot")) + " |", "|---|---|---|---|"]
    for model in loaded:
        row = []
        for ds in ("ctu13", "iot23", "medbiot"):
            vals = [out["per_scenario"][sc][model]["mcc"] for sc in out["per_scenario"]
                    if sc.startswith(ds) and 0 < yref[scen == sc].sum() < (scen == sc).sum()]
            row.append(f"{np.mean(vals):.3f} (n={len(vals)})" if vals else "—")
        md.append(f"| {model} | " + " | ".join(row) + " |")
    md.append("")

    # 4. host level
    md += ["## 4. Host-level detection (test set; a host is a (scenario, IP) pair)", "",
           "| Model | bot hosts | detected in ≥1 window | host recall | median delay (windows) | detected in first bot window |",
           "|---|---|---|---|---|---|"]
    for model, runs in loaded.items():
        h = host_level(runs[0]["y"], runs[0]["pred"], idx)
        out["host_level"][model] = h
        md.append(f"| {model} | {h['bot_hosts']} | {h['detected_hosts']} | {h['host_recall']:.4f} | "
                  f"{h['median_delay_windows']:.1f} | {h['share_detected_in_first_window']:.3f} |")
    md.append("")

    # 5. selection on validation
    cands = {
        "T-GINE + skip (P5)": "phase5_temporal_gine_skip.json",
        "P5 + SSL init": "phase5_temporal_gine_ssl_init.json",
        "DiffPool (P6)": "phase6_diffpool.json",
        "SAGPool (P6.4)": "phase6_sparse_baseline.json",
        "GT-edge (P7)": "phase7_higt_bot_edge.json",
        "GT-global (P7)": "phase7_higt_bot_global.json",
        "GT-hybrid 2L (P7)": "phase7_higt_bot_hybrid.json",
        "GT-hybrid 4L (P7)": "phase7_higt_bot_hybrid4.json",
    }
    rows = []
    for name, f in cands.items():
        p = INSPECTION / f
        if not p.exists():
            continue
        d = json.loads(p.read_text())
        v, t = d.get("val", {}), d.get("test", {})
        rows.append({"model": name, "val_f1": v.get("f1"), "val_pr_auc": v.get("pr_auc"),
                     "val_fn": v.get("fn"), "test_f1": t.get("f1"), "test_pr_auc": t.get("pr_auc"),
                     "test_fn": t.get("fn")})
    out["selection"] = rows
    by_val = sorted(rows, key=lambda r: -(r["val_f1"] or 0))
    by_test = sorted(rows, key=lambda r: -(r["test_f1"] or 0))
    md += ["## 5. Model selection on validation vs test", "",
           "| Candidate | val F1 | val PR-AUC | val FN | test F1 | test PR-AUC | test FN | rank (val F1) | rank (test F1) |",
           "|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        md.append(f"| {r['model']} | {r['val_f1']:.4f} | {r['val_pr_auc']:.4f} | {r['val_fn']} | "
                  f"{r['test_f1']:.4f} | {r['test_pr_auc']:.4f} | {r['test_fn']} | "
                  f"{by_val.index(r) + 1} | {by_test.index(r) + 1} |")
    md += ["", f"Selected by validation F1: **{by_val[0]['model']}**; by test F1: **{by_test[0]['model']}**.", ""]

    (INSPECTION / "tier1_reanalysis.md").write_text("\n".join(md), encoding="utf-8")
    (INSPECTION / "tier1_reanalysis.json").write_text(json.dumps(out, indent=2, default=float))
    print("\n".join(md))


if __name__ == "__main__":
    main()
